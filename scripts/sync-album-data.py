"""Generate the album list and assemble archived fMP4 covers for file:// playback."""

import json
from pathlib import Path
import re
from shutil import copyfileobj
from tempfile import TemporaryDirectory

from album_records import browser_record, local_asset_name, stored_albums

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "public" / "album-data.js"


def assemble_motion(folder, playlist):
    lines = playlist.read_text(encoding="utf-8").splitlines()
    maps = [line for line in lines if line.startswith("#EXT-X-MAP:")]
    init = re.fullmatch(r'#EXT-X-MAP:URI="(init-\d+\.mp4)"', maps[0]) if len(maps) == 1 else None
    segments = [line for line in lines if line and not line.startswith("#")]
    # Only concatenate a complete, continuous fMP4 stream with one initialization segment.
    unsupported_tags = ("#EXT-X-BYTERANGE", "#EXT-X-DISCONTINUITY", "#EXT-X-KEY:")
    if (not init or "#EXT-X-ENDLIST" not in lines or not segments
            or any(line.startswith(unsupported_tags) and line != "#EXT-X-KEY:METHOD=NONE" for line in lines)
            or not all(re.fullmatch(r"segment-\d+\.m4s", segment) for segment in segments)):
        return False

    parts = [folder / name for name in (init[1], *segments)]
    if not all(part.is_file() for part in parts):
        return False
    output = folder / "motion.mp4"
    if output.is_file() and output.stat().st_mtime_ns >= max(part.stat().st_mtime_ns for part in [playlist, *parts]):
        return True
    with TemporaryDirectory(dir=folder, prefix=".motion-") as temporary:
        staged = Path(temporary) / output.name
        with staged.open("wb") as media:
            for part in parts:
                with part.open("rb") as fragment:
                    copyfileobj(fragment, media)
        staged.replace(output)
    return True


def main():
    records = []
    for folder, record in stored_albums():
        album = browser_record(folder, record)
        playlist_name = local_asset_name(folder, record, "motionUrl")
        if playlist_name:
            playlist = folder / playlist_name
            if playlist.is_file() and assemble_motion(folder, playlist):
                album["motionFile"] = album["motionUrl"].removesuffix(playlist_name) + "motion.mp4"
            else:
                print(f"{folder.name}：无法生成本地动态封面，双击打开时将显示静态封面。")
        for field in ("cover", "motionUrl", "motionFile"):
            if field in album and album[field].startswith("/public/albums/"):
                album[field] = album[field][1:]
        records.append(album)
    records.sort(key=lambda record: (record["createdAt"], record["id"]))
    payload = json.dumps(records, ensure_ascii=False, indent=2)
    header = (
        "// Auto-generated by scripts/sync-album-data.py — do not edit by hand.\n"
        "// Provides window.ALBUM_DATA for the album shelf's local (no-service) mode.\n"
    )
    with TemporaryDirectory(dir=OUTPUT.parent, prefix=".album-data-") as temporary:
        staged = Path(temporary) / OUTPUT.name
        staged.write_text(header + "window.ALBUM_DATA = " + payload + ";\n", encoding="utf-8")
        staged.replace(OUTPUT)
    print(f"Wrote {OUTPUT.relative_to(ROOT)} with {len(records)} record(s).")


if __name__ == "__main__":
    main()
