#!/usr/bin/env python3
"""Build the static concert manifest from README and date-based local media."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONCERTS = ROOT / 'public' / 'concert'
IMAGES = {'.jpg', '.jpeg', '.png', '.webp', '.gif', '.avif', '.heic', '.heif'}
VIDEOS = {'.mov', '.mp4', '.m4v', '.webm'}


def url(path):
    return path.relative_to(ROOT).as_posix()


def fresh(source, target):
    return target.exists() and target.stat().st_size > 0 and target.stat().st_mtime >= source.stat().st_mtime


def photo_path(source):
    if source.suffix.lower() not in {'.heic', '.heif'}:
        return source
    target = source.parent / '_web' / (source.stem + '.jpg')
    if fresh(source, target):
        return target
    try:
        from PIL import Image, ImageOps
        from pillow_heif import register_heif_opener
    except ImportError as error:
        raise SystemExit('转换 HEIC 需要先运行：python3 -m pip install -r scripts/requirements.txt') from error
    register_heif_opener()
    target.parent.mkdir(exist_ok=True)
    with Image.open(source) as image:
        image = ImageOps.exif_transpose(image).convert('RGB')
        image.thumbnail((2400, 2400))
        image.save(target, quality=90, optimize=True)
    return target


def scan_media(folder, poster):
    """Pair only within the same directory; live originals are never converted."""
    live = folder / 'live'
    files = sorted(p for p in live.rglob('*') if p.is_file()
                   and not any(part.startswith('.') or part == '_web' for part in p.relative_to(live).parts))
    photos = [p for p in files if p.suffix.lower() in IMAGES]
    videos = {}
    for path in files:
        if path.suffix.lower() in VIDEOS:
            videos.setdefault((path.parent, path.stem.casefold()), []).append(path)
    used_videos = set()
    media = []
    for photo in photos:
        candidates = videos.get((photo.parent, photo.stem.casefold()), [])
        video = next((v for v in candidates if v.suffix.lower() == '.mov'), candidates[0] if candidates else None)
        item = dict(name=photo.relative_to(live).as_posix(), original=url(photo), kind='photo')
        if video:
            used_videos.add(video)
            item.update(kind='live', image=url(photo), video=url(video), videoOriginal=url(video))
        else:
            item['image'] = url(photo_path(photo))
        media.append(item)
    for candidates in videos.values():
        for video in candidates:
            if video not in used_videos:
                media.append(dict(name=video.relative_to(live).as_posix(), kind='video', image=poster, video=url(video)))
    return media


def read_records():
    records = {}
    for line in (ROOT / 'README.md').read_text().splitlines():
        cells = [value.strip() for value in line.strip('|').split('|')]
        if len(cells) < 7 or not re.fullmatch(r'\d{4}-\d{2}-\d{2}', cells[0]):
            continue
        date, title, artist, city, venue, seat, price = cells[:7]
        records[date] = dict(date=date, title=title, artist=artist, city=city,
                             venue=venue, seat=seat, price=price, note='')
    overrides = json.loads((CONCERTS / 'metadata.json').read_text()) if (CONCERTS / 'metadata.json').exists() else {}
    for date, fields in overrides.items():
        records[date] = {**records.get(date, {'date': date, 'seat': '', 'price': '', 'note': ''}), **fields}
    return records


def sync():
    records = read_records()
    missing = [folder.name for folder in CONCERTS.iterdir()
               if folder.is_dir() and re.fullmatch(r'\d{4}-\d{2}-\d{2}', folder.name)
               and folder.name not in records]
    if missing:
        raise SystemExit('以下日期缺少演出信息，请在 README 表格或 public/concert/metadata.json 补充：' + ', '.join(missing))
    for date, record in records.items():
        folder = CONCERTS / date
        record['id'] = 'concert-' + date
        posters = sorted(p for p in folder.glob('*') if p.stem.lower() == 'poster' and p.suffix.lower() in IMAGES)
        record['poster'] = url(photo_path(posters[0])) if posters else ''
        record['media'] = scan_media(folder, record['poster'])
    result = sorted(records.values(), key=lambda record: record['date'], reverse=True)
    (ROOT / 'public' / 'concert-data.js').write_text('// Generated by scripts/sync-concerts.py; edit README or concert/metadata.json.\nwindow.CONCERT_DATA = ' + json.dumps(result, ensure_ascii=False, indent=2) + ';\n')
    print(f'已整理 {len(result)} 场演出、{sum(len(r["media"]) for r in result)} 份现场素材。')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.parse_args()
    sync()
